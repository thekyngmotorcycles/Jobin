import assert from "node:assert/strict";
import test from "node:test";
import {readFileSync} from "node:fs";
const file=(path:string)=>readFileSync(path,"utf8");

test("My network is replaced by a notification bell and old links remain safe",()=>{
 const profile=file("src/app/(tabs)/profile.tsx");
 const bell=file("src/components/NotificationBell.tsx");
 const old=file("src/app/my-network.tsx");
 assert.ok(profile.includes("<NotificationBell/>"));
 assert.ok(!profile.includes('router.push("/my-network")'));
 assert.ok(bell.includes('router.push("/notifications")'));
 assert.ok(bell.includes("countPendingProfileAlerts"));
 assert.ok(old.includes('<Redirect href="/notifications"/>'));
});
test("Profile followers and following open a private accessible bottom sheet",()=>{
 const counts=file("src/components/ProfileFollowCounts.tsx");
 assert.ok(counts.includes("<BottomSheet visible={sheet&&!pendingRemove}"),"The private sheet is hidden while its confirmation is open");
 assert.ok(counts.includes("<JobeenNoticeDialog visible={sheet&&pendingRemove!==null}"),"The confirmation cannot overlap the network sheet");
 assert.ok(counts.includes("if(!contactMutation.current)setSheet(false)"),"The sheet cannot close during a contact mutation");
 assert.ok(counts.includes("viewer===userId"));
 assert.ok(counts.includes('option==="followers"'));
 assert.ok(counts.includes("loadConnections("));
 assert.ok(counts.includes("toggleFollow("));
 assert.ok(counts.includes("Buscar personas"));
});
test("Notifications show real account activity, filters, read status and routing",()=>{
 const screen=file("src/app/notifications.tsx");
 const api=file("src/lib/activity-notifications.ts");
 assert.ok(screen.includes('["Todas","Solicitudes","Sistema"]'));
 assert.ok(screen.includes("markActivityNotificationsRead("));
 assert.ok(screen.includes("loadActivityNotifications(100,scope)"));
 assert.ok(screen.includes("await assertMessageScope(scope)"),"Notifications are checked against the originating session");
 assert.ok(screen.includes("markActivityNotificationsRead(undefined,scope)"),"Mark all must not operate on a new account");
 assert.ok(screen.includes('"/message-requests"'));
 assert.ok(screen.includes('pathname:"/post/[id]"'));
 assert.ok(screen.includes('pathname:"/jcard"'));
 assert.ok(api.includes('from("notifications"'));
 assert.ok(api.includes('.is("read_at",null)'));
 assert.ok(api.includes("noticeDescription"));
 assert.ok(!screen.includes("DEMO"));
});
