import assert from "node:assert/strict";
import test from "node:test";
import {readFileSync} from "node:fs";
const src=(path:string)=>readFileSync(path,"utf8");
test("JCard and skeleton share the same responsive dimensions for small screens and text scaling",()=>{
 const metrics=src("src/theme/jcard.ts");
 const skeleton=src("src/components/JCardLoadingSkeleton.tsx");
 const card=src("src/components/JobinCard.tsx");
 assert.ok(metrics.includes("export function jcardSurfaceSize("));
 assert.ok(metrics.includes("lightHeight:330, darkHeight:400"));
 assert.ok(metrics.includes("compactHeightExtra:8"));
 assert.match(skeleton,/jcardSurfaceSize\(\{screenWidth,measuredWidth,fontScale,theme,profile:\{\}\}\)/);
 assert.match(card,/jcardSurfaceSize\(\{screenWidth:width,measuredWidth:measuredCardWidth,fontScale,theme:previewTheme\?\?theme,profile:profileSizing\}\)/);
 assert.ok(skeleton.includes("onLayout={event"));
 assert.ok(card.includes("onLayout={event"));
 assert.ok(!skeleton.includes("height:450"));
 assert.ok(skeleton.includes("maxWidth:jcardSurfaceMetrics.maxWidth"));
 assert.ok(card.includes("maxWidth:jcardSurfaceMetrics.maxWidth"));
 assert.ok(skeleton.includes("JobinLoadingGears"));
 assert.ok(skeleton.includes("Cargando JCard"));
});
test("JCard does not auto-flip, store tutorial markers or display a flip control",()=>{
 const card=src("src/components/JobinCard.tsx");
 const flip=src("src/components/BusinessCard3D.tsx");
 assert.ok(!card.includes("jobeen.jcard.flip.ghost"));
 assert.ok(!card.includes("ghostPreview="));
 assert.ok(!card.includes("AsyncStorage"));
 assert.ok(!card.includes('name="hand-left-outline"'));
 assert.ok(!card.includes('name="sync-outline"'));
 assert.ok(!card.includes("Toca o desliza para girar"));
 assert.ok(flip.includes("Gesture.Exclusive(pan,tap)"));
 assert.ok(flip.includes("CardFlipInteractionContext.Provider"));
 assert.ok(card.includes('onSideChange={side=>setBack(side==="business")}'));
});
test("Hexagonal gears share one animation clock, are monochrome and respect reduced motion/offline",()=>{
 const gears=src("src/components/JobinLoadingGears.tsx");
 assert.ok(gears.includes('mode?:"loading"|"offline"'));
 assert.ok(gears.includes('if(mode!=="loading"||reducedMotion)return;'));
 assert.ok(gears.includes("withRepeat(withTiming(360"));
 assert.ok(gears.includes("cancelAnimation(progress)"));
 assert.equal((gears.match(/useSharedValue\(0\)/g)??[]).length,1);
 assert.equal((gears.match(/direction:-1/g)??[]).length,2);
 assert.equal((gears.match(/direction:1/g)??[]).length,1);
 assert.ok(gears.includes("length:6"));
 assert.ok(gears.includes('fill="none"'));
 assert.ok(gears.includes("color={t.ink2}"));
 assert.ok(!gears.includes("t.yellow"));
 assert.ok(!gears.includes("translateX"));
 assert.ok(!gears.includes("backgroundColor"));
 assert.ok(!gears.includes("fetch("));
 assert.ok(gears.includes("accessibilityElementsHidden"));
 assert.ok(src("src/components/JCardConnectionState.tsx").includes('<JobinLoadingGears mode="offline"'));
});
test("Offline JCard is distinct from endless loading and provides a retry or cached card",()=>{
 const state=src("src/components/JCardConnectionState.tsx");
 const profile=src("src/app/(tabs)/profile.tsx");
 const publicProfile=src("src/app/jcard.tsx");
 assert.ok(state.includes("export function isJCardConnectivityError"));
 assert.ok(state.includes('if(loading)return <JCardLoadingSkeleton/>'));
 assert.ok(state.includes('if(error&&isJCardConnectivityError(error))return <JCardOfflineNotice retry={retry}/>'));
 assert.ok(state.includes('mode="offline"'));
 assert.ok(state.includes("Reintentar"));
 assert.ok(state.includes("Mostrando la última JCard guardada"));
 assert.ok(profile.includes("JCardOfflineNotice retry={workspace.reload} cached"));
 assert.ok(publicProfile.includes("JCardLoadState loading={resource.loading} error={resource.error}"));
});
